use super::traits::GeneratedArtifact;
use anyhow::{Result, bail};
use std::collections::BTreeMap;
use std::path::PathBuf;

pub struct CollisionDetector;

impl CollisionDetector {
    /// Validates that there are no conflicting file collisions among generated artifacts.
    pub fn verify_no_collisions(artifacts: &[GeneratedArtifact]) -> Result<()> {
        let mut seen: BTreeMap<&PathBuf, &GeneratedArtifact> = BTreeMap::new();

        for artifact in artifacts {
            if let Some(previous) = seen.get(&artifact.relative_path) {
                bail!(
                    "Duplicate generated path '{:?}': generated by '{}' ({}) and '{}' ({}). Each output path must have exactly one owner.",
                    artifact.relative_path,
                    previous.provider,
                    previous.target_os,
                    artifact.provider,
                    artifact.target_os
                );
            } else {
                seen.insert(&artifact.relative_path, artifact);
            }
        }

        Ok(())
    }
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::target::{OsTarget, ProviderTarget};

    #[test]
    fn test_collision_on_same_content() {
        let art1 = GeneratedArtifact {
            provider: ProviderTarget::Claude,
            target_os: OsTarget::new("linux").expect("linux is a valid test OS"),
            relative_path: PathBuf::from("SHARED.md"),
            content: "hello".into(),
            is_executable: false,
        };
        let art2 = GeneratedArtifact {
            provider: ProviderTarget::Gemini,
            target_os: OsTarget::new("linux").expect("linux is a valid test OS"),
            relative_path: PathBuf::from("SHARED.md"),
            content: "hello".into(),
            is_executable: false,
        };

        assert!(CollisionDetector::verify_no_collisions(&[art1, art2]).is_err());
    }

    #[test]
    fn test_collision_on_different_content() {
        let art1 = GeneratedArtifact {
            provider: ProviderTarget::Claude,
            target_os: OsTarget::new("linux").expect("linux is a valid test OS"),
            relative_path: PathBuf::from("CONFIG.json"),
            content: "{}".into(),
            is_executable: false,
        };
        let art2 = GeneratedArtifact {
            provider: ProviderTarget::Gemini,
            target_os: OsTarget::new("linux").expect("linux is a valid test OS"),
            relative_path: PathBuf::from("CONFIG.json"),
            content: "{\"diff\": true}".into(),
            is_executable: false,
        };

        assert!(CollisionDetector::verify_no_collisions(&[art1, art2]).is_err());
    }
}
