use crate::emitters::traits::GeneratedArtifact;
use crate::ir::WorkspaceContext;
use crate::target::{OsTarget, ProviderTarget};
use std::path::PathBuf;

pub struct AgentsMdEmitter;

impl AgentsMdEmitter {
    /// Emits the `.agents/AGENTS.md` artifact containing workspace guidelines and roles.
    pub fn emit(context: &WorkspaceContext, target_os: &OsTarget) -> GeneratedArtifact {
        let mut content = String::new();
        content.push_str("# Project Guidelines & Directives\n");
        content.push_str("<!-- Auto-generated by Arc (Agent Runtime Customization) -->\n\n");

        if let Some(ref instructions) = context.instructions_content {
            content.push_str("## Workspace Instructions\n\n");
            content.push_str(instructions.trim());
            content.push_str("\n\n");
        }

        if !context.roles.is_empty() {
            content.push_str("## Declared Roles & Personas\n\n");
            for (role_name, role) in &context.roles {
                content.push_str(&format!("### Role: `{}`\n", role_name));
                content.push_str(&format!("{}\n\n", role.description.trim()));
                if let Some(ref role_content) = role.content {
                    content.push_str("```markdown\n");
                    content.push_str(role_content.trim());
                    content.push_str("\n```\n\n");
                }
            }
        }

        GeneratedArtifact {
            provider: ProviderTarget::Gemini,
            target_os: target_os.clone(),
            relative_path: PathBuf::from(".agents/AGENTS.md"),
            content,
            is_executable: false,
        }
    }
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::ir::BoundRole;
    use std::collections::BTreeMap;

    #[test]
    fn test_agents_md_emission() {
        let mut roles = BTreeMap::new();
        roles.insert(
            "dev".to_string(),
            BoundRole {
                description: "Lead developer".into(),
                src_path: None,
                content: Some("Follow TDD".into()),
            },
        );

        let ctx = WorkspaceContext {
            workdir: PathBuf::from("."),
            instructions_path: None,
            instructions_content: Some("Always write tests".into()),
            roles,
        };

        let artifact = AgentsMdEmitter::emit(
            &ctx,
            &OsTarget::new("windows").expect("windows is a valid test OS"),
        );
        assert_eq!(artifact.relative_path, PathBuf::from(".agents/AGENTS.md"));
        assert!(artifact.content.contains("Always write tests"));
        assert!(artifact.content.contains("### Role: `dev`"));
        assert!(artifact.content.contains("Follow TDD"));
    }
}
