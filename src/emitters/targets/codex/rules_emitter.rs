use anyhow::{Result, bail};
use std::path::PathBuf;

use crate::emitters::traits::GeneratedArtifact;
use crate::ir::BoundToolGuard;
use crate::manifest::schema::ActionType;
use crate::target::{OsTarget, ProviderTarget};

pub struct RulesEmitter;

#[derive(Debug, Clone, PartialEq, Eq)]
pub enum RuleCompilation {
    Representable { argv: Vec<String> },
    Unsupported { reason: String },
}

impl RulesEmitter {
    pub fn emit_rules(
        tool_guards: &[BoundToolGuard],
        target_os: &OsTarget,
    ) -> Result<Option<GeneratedArtifact>> {
        let mut rules = Vec::new();

        for guard in tool_guards
            .iter()
            .filter(|guard| guard.on_failure.action == ActionType::Ask)
        {
            if !guard.matcher.regex_patterns.is_empty() {
                bail!(
                    "Codex ask guard '{}' is unsupported: regex matchers cannot be represented by prefix_rule. Use exact command patterns or change on_failure.action to deny.",
                    guard.id
                );
            }
            if guard.matcher.exact_patterns.is_empty() {
                bail!(
                    "Codex ask guard '{}' is unsupported: it has no exact command patterns. Add an exact command matcher or change on_failure.action to deny.",
                    guard.id
                );
            }

            for exact in &guard.matcher.exact_patterns {
                let argv = match compile_exact_pattern(exact) {
                    RuleCompilation::Representable { argv } => argv,
                    RuleCompilation::Unsupported { reason } => {
                        bail!(
                            "Codex ask guard '{}' pattern {:?} is unsupported: {}. Use a static exact command or change on_failure.action to deny.",
                            guard.id,
                            exact,
                            reason
                        )
                    }
                };
                rules.push(render_rule(
                    &guard.id,
                    exact,
                    &argv,
                    guard.on_failure.feedback.as_deref(),
                )?);
            }
        }

        if rules.is_empty() {
            return Ok(None);
        }

        let content = format!(
            "# Auto-generated by Arc. Do not edit; regenerate from arc.yaml.\n# Codex rules are experimental. Each ask guard prompts for every matching prefix.\n\n{}\n",
            rules.join("\n\n")
        );
        Ok(Some(GeneratedArtifact {
            provider: ProviderTarget::Codex,
            target_os: target_os.clone(),
            relative_path: PathBuf::from(".codex/rules/arc-generated.rules"),
            content,
            is_executable: false,
        }))
    }
}

pub fn compile_exact_pattern(pattern: &str) -> RuleCompilation {
    const SHELL_META: &[char] = &['|', '&', ';', '<', '>', '$', '`', '*', '?', '\n', '\r'];
    if pattern.trim().is_empty() {
        return RuleCompilation::Unsupported {
            reason: "empty command".into(),
        };
    }
    if pattern.chars().any(|c| SHELL_META.contains(&c)) {
        return RuleCompilation::Unsupported {
            reason: "shell operators, expansion, redirects, or wildcards are not allowed".into(),
        };
    }

    match tokenize_static_command(pattern) {
        Ok(argv) if !argv.is_empty() => RuleCompilation::Representable { argv },
        Ok(_) => RuleCompilation::Unsupported {
            reason: "empty command".into(),
        },
        Err(reason) => RuleCompilation::Unsupported { reason },
    }
}

fn tokenize_static_command(input: &str) -> std::result::Result<Vec<String>, String> {
    let mut argv = Vec::new();
    let mut current = String::new();
    let mut quote = None;
    let mut chars = input.chars().peekable();

    while let Some(ch) = chars.next() {
        match quote {
            Some(q) if ch == q => quote = None,
            Some('"') if ch == '\\' && chars.peek() == Some(&'"') => {
                chars.next();
                current.push('"');
            }
            Some(_) => current.push(ch),
            None if ch == '\'' || ch == '"' => quote = Some(ch),
            None if ch.is_whitespace() => {
                if !current.is_empty() {
                    argv.push(std::mem::take(&mut current));
                }
            }
            None => current.push(ch),
        }
    }

    if quote.is_some() {
        return Err("unclosed quoted argument".into());
    }
    if !current.is_empty() {
        argv.push(current);
    }
    Ok(argv)
}

fn render_rule(
    guard_id: &str,
    exact: &str,
    argv: &[String],
    feedback: Option<&str>,
) -> Result<String> {
    let pattern = serde_json::to_string(argv)?;
    let matches = serde_json::to_string(&vec![exact])?;
    let mut non_match = argv.to_vec();
    non_match[0].push_str("-arc-non-match");
    let non_match_command = non_match.join(" ");
    let not_matches = serde_json::to_string(&vec![non_match_command])?;
    let justification = feedback
        .map(str::to_owned)
        .unwrap_or_else(|| format!("Arc guard '{}' requires approval", guard_id));

    Ok(format!(
        "# Arc guard: {}\nprefix_rule(\n    pattern = {},\n    decision = \"prompt\",\n    justification = {},\n    match = {},\n    not_match = {},\n)",
        guard_id,
        pattern,
        serde_json::to_string(&justification)?,
        matches,
        not_matches
    ))
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::ir::{BoundMatcher, BoundRuleExpression};
    use crate::manifest::schema::OnFailureConfig;

    fn ask_guard(matcher: BoundMatcher) -> BoundToolGuard {
        BoundToolGuard {
            id: "approve_push".into(),
            matcher,
            require: BoundRuleExpression::Decide {
                prompt: "approve?".into(),
            },
            on_failure: OnFailureConfig {
                action: ActionType::Ask,
                feedback: Some("Approve force push".into()),
            },
            order: 0,
            declaration_order: 0,
        }
    }

    #[test]
    fn emits_prompt_rule_for_static_exact_command() {
        let artifact = RulesEmitter::emit_rules(
            &[ask_guard(BoundMatcher {
                exact_patterns: vec!["git push --force origin main".into()],
                regex_patterns: vec![],
            })],
            &OsTarget::new("windows").expect("windows is a valid test OS"),
        )
        .unwrap()
        .unwrap();
        assert_eq!(
            artifact.relative_path,
            PathBuf::from(".codex/rules/arc-generated.rules")
        );
        assert!(artifact.content.contains("decision = \"prompt\""));
        assert!(
            artifact
                .content
                .contains("[\"git\",\"push\",\"--force\",\"origin\",\"main\"]")
        );
    }

    #[test]
    fn rejects_regex_and_shell_syntax() {
        let regex_err = RulesEmitter::emit_rules(
            &[ask_guard(BoundMatcher {
                exact_patterns: vec![],
                regex_patterns: vec!["git push .*".into()],
            })],
            &OsTarget::new("linux").expect("linux is a valid test OS"),
        )
        .unwrap_err();
        assert!(regex_err.to_string().contains("regex matchers"));

        assert!(matches!(
            compile_exact_pattern("git push && echo unsafe"),
            RuleCompilation::Unsupported { .. }
        ));
    }
}
