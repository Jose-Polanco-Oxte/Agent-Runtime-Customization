use anyhow::Result;
use serde_json::{Value, json};
use std::collections::BTreeMap;
use std::path::{Path, PathBuf};

use crate::emitters::traits::GeneratedArtifact;
use crate::ir::{BoundLifecycleGuard, BoundToolGuard};
use crate::manifest::schema::LifecycleTrigger;
use crate::manifest::schema::RuntimeConfig;
use crate::target::{DecisionUiMode, OsTarget, ProviderTarget};

pub struct HooksEmitter;

impl HooksEmitter {
    /// Emits the project-local `.codex/hooks.json` artifact for Codex.
    pub fn emit_hooks(
        lifecycle_guards: &[BoundLifecycleGuard],
        tool_guards: &[BoundToolGuard],
        target_os: &OsTarget,
        decision_ui: DecisionUiMode,
        custom_arc_bin: Option<&str>,
        runtime: &RuntimeConfig,
        ir_path: &Path,
    ) -> Result<Vec<GeneratedArtifact>> {
        let mut artifacts = Vec::new();

        let arc_cmd = custom_arc_bin
            .map(|s| s.to_string())
            .or_else(|| std::env::var("ARC_BIN").ok())
            .unwrap_or_else(|| "arc".to_string());
        let command = |event: &str| {
            format!(
                "{} hook run --event-type {} --provider codex --decision-ui {} --ir-path {}",
                quote_posix_arg(&arc_cmd),
                event,
                decision_ui,
                quote_posix_arg(&ir_path.to_string_lossy())
            )
        };
        let command_windows =
            |event: &str| windows_hook_command(&arc_cmd, event, decision_ui, ir_path);

        let mut hooks_map = BTreeMap::new();

        // 1. PreToolUse Hook (if tool guards exist)
        if !tool_guards.is_empty() {
            hooks_map.insert(
                "PreToolUse",
                json!([
                    {
                        "matcher": "*",
                        "hooks": [
                            {
                                "type": "command",
                                "command": command("pre-tool-use"),
                                "commandWindows": command_windows("pre-tool-use"),
                                "timeout": runtime.hook_timeout_seconds(),
                                "statusMessage": "Evaluating Arc tool guard policy"
                            }
                        ]
                    }
                ]),
            );
        }

        // 2. SessionStart Hook (if start trigger exists)
        let has_start = lifecycle_guards
            .iter()
            .any(|g| g.triggers.contains(&LifecycleTrigger::Start));

        if has_start {
            hooks_map.insert(
                "SessionStart",
                json!([
                    {
                        "hooks": [
                            {
                                "type": "command",
                                "command": command("session-start"),
                                "commandWindows": command_windows("session-start"),
                                "timeout": runtime.hook_timeout_seconds(),
                                "statusMessage": "Evaluating Arc session start policy"
                            }
                        ]
                    }
                ]),
            );
        }

        // 3. Stop Hook (if end trigger exists)
        let has_end = lifecycle_guards
            .iter()
            .any(|g| g.triggers.contains(&LifecycleTrigger::End));

        if has_end {
            hooks_map.insert(
                "Stop",
                json!([
                    {
                        "hooks": [
                            {
                                "type": "command",
                                "command": command("stop"),
                                "commandWindows": command_windows("stop"),
                                "timeout": runtime.hook_timeout_seconds(),
                                "statusMessage": "Evaluating Arc session completion policy"
                            }
                        ]
                    }
                ]),
            );
        }

        if !hooks_map.is_empty() {
            let mut root = serde_json::Map::new();
            root.insert(
                "description".to_string(),
                Value::String(
                    "Auto-generated by Arc: runtime guard hooks for OpenAI Codex".to_string(),
                ),
            );

            let hooks_obj: serde_json::Map<String, Value> = hooks_map
                .into_iter()
                .map(|(k, v)| (k.to_string(), v))
                .collect();
            root.insert("hooks".to_string(), Value::Object(hooks_obj));

            let content =
                serde_json::to_string_pretty(&Value::Object(root)).expect("Valid hooks JSON");

            artifacts.push(GeneratedArtifact {
                provider: ProviderTarget::Codex,
                target_os: target_os.clone(),
                relative_path: PathBuf::from(".codex/hooks.json"),
                content,
                is_executable: false,
            });
        }

        Ok(artifacts)
    }
}

fn quote_posix_arg(value: &str) -> String {
    if value
        .chars()
        .all(|c| c.is_ascii_alphanumeric() || matches!(c, '_' | '-' | '/' | '.' | ':'))
    {
        value.to_string()
    } else {
        format!("'{}'", value.replace('\'', "'\"'\"'"))
    }
}

fn windows_hook_command(
    arc_cmd: &str,
    event: &str,
    decision_ui: DecisionUiMode,
    ir_path: &Path,
) -> String {
    let ir_path = ir_path.to_string_lossy();
    if ir_path.contains('"') || ir_path.contains(['\r', '\n']) {
        return "cmd.exe /D /C exit 2".to_string();
    }
    let quoted_ir_path = if ir_path.chars().any(char::is_whitespace) {
        format!("\"{ir_path}\"")
    } else {
        ir_path.into_owned()
    };
    let suffix = format!(
        "hook run --event-type {} --provider codex --decision-ui {} --ir-path {}",
        event, decision_ui, quoted_ir_path
    );
    if arc_cmd.contains('"') || arc_cmd.contains(['\r', '\n']) {
        // This can only originate in an explicit ARC_BIN/custom setting. Emit a
        // command that fails visibly instead of accepting command injection.
        return "cmd.exe /D /C exit 2".to_string();
    }
    if arc_cmd.chars().any(char::is_whitespace) {
        format!("cmd.exe /D /S /C \"\"{}\" {}\"", arc_cmd, suffix)
    } else {
        format!("{} {}", arc_cmd, suffix)
    }
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::ir::{BoundMatcher, BoundRuleExpression};
    use crate::manifest::schema::{ActionType, OnFailureConfig};

    #[test]
    fn test_codex_hooks_json_emission() {
        let tool_guards = vec![BoundToolGuard {
            id: "guard_push".into(),
            matcher: BoundMatcher::default(),
            require: BoundRuleExpression::Decide {
                prompt: "ok?".into(),
            },
            on_failure: OnFailureConfig {
                action: ActionType::Deny,
                feedback: None,
            },
            order: 0,
            declaration_order: 0,
        }];

        let lifecycle_guards = vec![BoundLifecycleGuard {
            id: "guard_end".into(),
            triggers: vec![LifecycleTrigger::End],
            require: BoundRuleExpression::Decide {
                prompt: "clean?".into(),
            },
            on_failure: OnFailureConfig {
                action: ActionType::Deny,
                feedback: None,
            },
            order: 0,
            declaration_order: 0,
        }];

        let runtime = RuntimeConfig {
            decision_timeout_seconds: 37,
        };
        let artifacts = HooksEmitter::emit_hooks(
            &lifecycle_guards,
            &tool_guards,
            &OsTarget::new("windows").expect("windows is a valid test OS"),
            DecisionUiMode::Auto,
            None,
            &runtime,
            Path::new("C:/workspace/.codex/arc_ir.json"),
        )
        .unwrap();

        assert_eq!(artifacts.len(), 1);
        let hooks_art = artifacts
            .iter()
            .find(|a| a.relative_path == PathBuf::from(".codex/hooks.json"))
            .unwrap();

        assert_eq!(hooks_art.provider, ProviderTarget::Codex);
        assert!(hooks_art.content.contains("PreToolUse"));
        assert!(hooks_art.content.contains("Stop"));
        assert!(!hooks_art.content.contains("SessionStart"));
        assert!(
            hooks_art
                .content
                .contains("--ir-path C:/workspace/.codex/arc_ir.json")
        );
        assert!(hooks_art.content.contains("commandWindows"));
        assert!(hooks_art.content.contains("\"timeout\": 222"));
        assert!(
            hooks_art
                .content
                .contains("\"commandWindows\": \"arc hook run")
        );

        let value: Value = serde_json::from_str(&hooks_art.content).unwrap();
        let hooks = value.get("hooks").unwrap();
        for event in ["PreToolUse", "Stop"] {
            let groups = hooks.get(event).unwrap().as_array().unwrap();
            assert!(groups[0].get("hooks").unwrap().is_array());
        }
    }

    #[test]
    fn quotes_windows_arc_path_with_spaces_via_cmd() {
        let command = windows_hook_command(
            "C:\\Program Files\\Arc\\arc.exe",
            "pre-tool-use",
            DecisionUiMode::Auto,
            Path::new("C:\\Project Space\\.codex\\arc_ir.json"),
        );
        assert_eq!(
            command,
            "cmd.exe /D /S /C \"\"C:\\Program Files\\Arc\\arc.exe\" hook run --event-type pre-tool-use --provider codex --decision-ui auto --ir-path \"C:\\Project Space\\.codex\\arc_ir.json\"\""
        );
    }
}
